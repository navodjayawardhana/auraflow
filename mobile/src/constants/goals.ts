/**
 * Daily targets.
 *
 * Fixed rather than personalised, and worth being honest about why: personalising a step
 * goal properly needs a baseline the app does not yet have, and personalising a hydration
 * goal properly needs body mass, climate and activity. A defensible default beats a
 * bespoke number derived from nothing.
 */

/** The familiar 10,000 — a marketing figure originally, but a recognisable anchor. */
export const STEP_GOAL = 10_000;

/** Roughly eight glasses; the amount most adult guidance converges on. */
export const WATER_GOAL_ML = 2_000;

/** One tap on the water tracker. */
export const GLASS_ML = 250;
